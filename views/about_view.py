"""views/about_view.py — Scientific background, mathematical formulations, and chemometric documentation."""
import streamlit as st


def render_about_page():
    st.markdown("## 📖 О проекте SpectraMatch & Научные основы")
    st.markdown(
        "**SpectraMatch** — исследовательская аналитическая платформа для мультимодальной "
        "хемометрической идентификации и биогеохимического профилирования сложного природного "
        "органического вещества (Natural / Dissolved Organic Matter — NOM/DOM)."
    )

    tab_chem, tab_math, tab_indices, tab_standards = st.tabs(
        [
            "🧪 Спектроскопия DOM",
            "📐 Математика сходства",
            "🔬 Хемометрические индексы",
            "🏛️ Стандарты IHSS и цитирование",
        ]
    )

    with tab_chem:
        st.markdown(
            r"""
            ### Природное органическое вещество (NOM / DOM)
            Природное органическое вещество водной и почвенной среды представляет собой полидисперсную 
            смесь миллионов индивидуальных соединений (гуминовые и фульвокислоты, лигнины, полисахариды, 
            пептиды и липиды). Для его комплексной характеризации в современной хемометрике применяется 
            три взаимодополняющих спектральных метода:

            1. **ИК-Фурье спектроскопия (FTIR):**
               Отражает интегральный колебательный состав функциональных групп:
               - $3400\text{ см}^{-1}$ — водородно-связанные гидроксилы ($\text{O}-\text{H}$);
               - $2925, 2850\text{ см}^{-1}$ — алифатические связи $\text{C}-\text{H}$ ($-\text{CH}_2-, -\text{CH}_3$);
               - $1715\text{ см}^{-1}$ — карбонилы и карбоксилы ($-\text{COOH}, \text{C}=\text{O}$);
               - $1600\text{ см}^{-1}$ — ароматический каркас ($\text{C}=\text{C}$);
               - $1510\text{ см}^{-1}$ — специфическое кольцевое колебание лигнина;
               - $1030\text{ см}^{-1}$ — полисахаридные эфирные связи ($\text{C}-\text{O}-\text{C}$).

            2. **2D Флуоресценция Excitation-Emission Matrix (EEM):**
               Двумерная оптическая спектроскопия, фиксирующая эмиссию флуорофоров в диапазоне 
               $Ex \in [240, 450]\text{ нм}$ и $Em \in [280, 600]\text{ нм}$. Позволяет различать 
               автохтонное микробное вещество и аллохтонные терригенные гуминовые кислоты.

            3. **FT-ICR MS (Масс-спектрометрия сверхвысокого разрешения):**
               Прямое определение молекулярных формул сотен тысяч ионов в диапазоне $150–800\text{ Да}$ 
               с точностью до субмиллионных долей ($< 0.5\text{ ppm}$).
            """
        )

    with tab_math:
        st.markdown(
            r"""
            ### Математические метрики спектрального сопоставления

            #### 1. Косинусное сходство (Cosine Similarity)
            $$\mathcal{S}_{\cos}(\mathbf{q}, \mathbf{r}) = \frac{\mathbf{q} \cdot \mathbf{r}}{\|\mathbf{q}\|_2 \|\mathbf{r}\|_2}$$
            Для предварительно $L_2$-нормированных векторов библиотечный поиск сводится к сверхбыстрому 
            матрично-векторному умножению: $\mathbf{s} = \mathbf{R} \mathbf{q}$.

            #### 2. Корреляция Пирсона (Pearson Correlation Coefficient)
            $$r(\mathbf{q}, \mathbf{r}) = \frac{\sum_{i=1}^D (q_i - \bar{q})(r_i - \bar{r})}{\sqrt{\sum_{i=1}^D (q_i - \bar{q})^2} \sqrt{\sum_{i=1}^D (r_i - \bar{r})^2}}$$
            *Почему рекомендована для FTIR:* Центрирование спектров вычитает постоянную составляющую, 
            делая оценку строго инвариантной к остаточному сдвигу базовой линии (baseline offset).

            #### 3. Евклидово подобие (Euclidean Similarity)
            $$\mathcal{S}_{\text{euc}}(\mathbf{q}, \mathbf{r}) = \frac{1}{1 + \|\mathbf{q} - \mathbf{r}\|_2}$$
            Монотонно убывающая функция расстояния в нормированном пространстве признаков.

            #### 4. Коэффициент конгруэнтности Такера (Tucker Congruence Coefficient — TCC)
            Стандарт сопоставления флуоресцентных компонент **OpenFluor**. Вычисляет согласованность 
            раздельно по профилю возбуждения ($Ex$) и испускания ($Em$), гарантируя соответствие обоих оптических каналов:
            $$\text{TCC}(\mathbf{Q}, \mathbf{R}) = \min \left( \mathcal{S}_{\cos}(\mathbf{q}_{ex}, \mathbf{r}_{ex}), \, \mathcal{S}_{\cos}(\mathbf{q}_{em}, \mathbf{r}_{em}) \right)$$
            - $\text{TCC} \ge 0.95$ — идентичный флуорофор;
            - $\text{TCC} \ge 0.90$ — высокая степень структурного сходства;
            - $\text{TCC} < 0.80$ — различные оптические компоненты.
            """
        )

    with tab_indices:
        st.markdown(
            r"""
            ### Хемометрические дескрипторы

            #### FTIR индексы
            - **Lignin Index ($LI$):** $LI = \frac{A_{1510}}{A_{1600}}$ (доля технического и нативного лигнина);
            - **Aromaticity-to-Polysaccharide ($AI$):** $AI = \frac{A_{1510}}{A_{1030}}$ (соотношение ароматики и углеводов);
            - **Condensation Index ($CI$):** $CI = \frac{A_{1600}}{A_{1715}}$ (степень конденсации и окисленности).

            #### EEM биогеохимические индексы
            - **Fluorescence Index ($FI$, McKnight et al., 2001):**
              $$FI = \left. \frac{I(Em = 450)}{I(Em = 500)} \right|_{Ex = 370}$$
              $1.2–1.4$ — терригенное почвенное DOM; $1.7–2.0$ — водорослевое/микробное DOM.
            - **Humification Index ($HIX$, Ohno, 2002):**
              $$HIX = \left. \frac{\int_{435}^{480} I(Em) dEm}{\int_{300}^{345} I(Em) dEm} \right|_{Ex = 254}$$
            - **Biological Index ($BIX$, Huguet et al., 2009):**
              $$BIX = \left. \frac{I(Em = 380)}{I(Em = 430)} \right|_{Ex = 310}$$

            #### FT-ICR MS молекулярная масса
            - Средневзвешенная молекулярная масса: $\bar{M}_w = \frac{\sum m_i I_i}{\sum I_i}$;
            - Среднечисловая молекулярная масса: $\bar{M}_n = \frac{\sum I_i}{\sum (I_i / m_i)}$;
            - Полидисперсность: $PD = \bar{M}_w / \bar{M}_n$.
            """
        )

    with tab_standards:
        st.markdown(
            """
            ### Международные стандарты IHSS
            В базу данных включены канонические стандарты International Humic Substances Society:
            - **Suwannee River Fulvic Acid (SRFA 2S101F)**
            - **Suwannee River Humic Acid (SRHA 2S101H)**
            - **Elliott Soil Humic Acid (ESHA 4S102H)**
            - **Pahokee Peat Humic Acid (PPHA 1S103H)**

            ### Академическое использование
            Платформа спроектирована по стандартам воспроизводимых вычислений (Reproducible Research). 
            Все алгоритмы реализованы на чистом стеке `NumPy` и `SciPy` без скрытых эвристик.
            """
        )
